/**
 * 校验 AI 生成的四轴质量：
 * - 轴名不能超过6字
 * - 四个轴名不能重复
 * - 没有通过则返回 false
 */
export function validateAxes(axes: CharacterDNA["axes"]): boolean {
  if (!axes || axes.length < 4) return false;
  const keys = axes.map(a => a.key);
  const uniqueKeys = new Set(keys);
  if (uniqueKeys.size < keys.length) return false; // 有重复
  if (keys.some(k => k.length > 6)) return false;  // 轴名过长
  return true;
}

/**
 * 根据场域关键词找最接近的通用原型兜底
 */
export function pickArchetype(domains: string[]): typeof CHARACTER_ARCHETYPES[0] {
  if (domains.includes("感情关系")) return CHARACTER_ARCHETYPES[2];
  if (domains.includes("职场权力") && domains.includes("生存底线")) return CHARACTER_ARCHETYPES[0];
  if (domains.includes("身份认同") && domains.includes("职场权力")) return CHARACTER_ARCHETYPES[1];
  if (domains.includes("生存底线")) return CHARACTER_ARCHETYPES[3];
  return CHARACTER_ARCHETYPES[4]; // 默认谋略者原型
}
